import assert from 'node:assert/strict';
import {buildMatchReport, reportStats, finishReasonText} from '../src/prototype/match-report.js';

const yours=[{row:1,col:1,hit:true},{row:1,col:2,hit:false},{row:2,col:2,hit:false}];
const rivals=[{row:5,col:5,hit:false},{row:5,col:6,hit:true,sunkShip:'SEARCH'},{row:6,col:6,hit:false}];
const player1=buildMatchReport({winnerId:17,finishReason:'TIME_LIMIT',shotsFired:yours,shotsReceived:rivals},13);
const player2=buildMatchReport({winnerId:17,finishReason:'TIME_LIMIT',shotsFired:rivals,shotsReceived:yours},17);
assert.equal(player1.won,false);
assert.equal(player2.won,true);
assert.equal(player1.comparable,true);
assert.equal(player2.comparable,true);
assert.deepEqual(player1.player,player2.rival,'Rival must see inverted shot history');
assert.deepEqual(player1.rival,player2.player,'Both players must see consistent stats');
assert.equal(player1.player.hits,1);
assert.equal(player1.rival.hits,1);
assert.equal(player1.player.sunk,0);
assert.equal(player1.rival.sunk,1);
assert.match(player1.reason,/preservou mais navios/);
assert.match(finishReasonText('ABANDONED',17,13),/desistência/);
assert.match(finishReasonText('DISCONNECT_TIMEOUT',17,17),/não retornou/);
assert.match(finishReasonText('TURN_TIMEOUT_FORFEIT',17,17),/turnos/);
assert.match(finishReasonText('TIME_LIMIT_DRAW',null,13),/mesmo número/);
const blocked=reportStats([{row:0,col:0,hit:false,blocked:true},{row:0,col:1,hit:true},{row:0,col:2,hit:false}]);
assert.equal(blocked.attempts,2);
assert.equal(blocked.hits,1);
assert.equal(blocked.misses,1);
assert.equal(blocked.accuracy,50);
assert.equal(blocked.blocked,1);
console.log('PASS match report: mirrored perspectives, tied shots with different result, finish reason, blocked shots');
