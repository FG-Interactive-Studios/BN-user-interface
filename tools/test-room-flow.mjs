import assert from 'node:assert/strict';
import { roomDeparture, resolvedRoute } from '../src/prototype/room-flow.js';
const together = { code:'ABC234', status:'WAITING', players:[{id:1},{id:2}] };
const alone = { ...together, players:[{id:1, ready:false}] };
assert.equal(roomDeparture(together,alone,1),'guest-left');
assert.equal(roomDeparture(together,null,2),'host-left');
assert.equal(roomDeparture({...together,status:'PREPARING'},alone,1),'guest-left');
assert.equal(roomDeparture({...together,status:'PREPARING'},null,2),'host-left');
assert.equal(roomDeparture(together,null,1),null);
assert.equal(roomDeparture(together,alone,2),null);
assert.equal(roomDeparture(alone,alone,1),null);
assert.equal(roomDeparture(together,together,1),null);
assert.equal(roomDeparture({...together,status:'PLAYING'},null,2),null);
assert.equal(roomDeparture(together,{...alone,code:'OTHER1'},1),null);
assert.equal(roomDeparture(together,{...alone,players:[{id:2}]},1),null);
assert.equal(resolvedRoute('auth',true),'lobby');
assert.equal(resolvedRoute('register',true,'WAITING'),'matchmaking');
assert.equal(resolvedRoute('auth',true,'PLAYING'),'match');
assert.equal(resolvedRoute('auth',false),'auth');
