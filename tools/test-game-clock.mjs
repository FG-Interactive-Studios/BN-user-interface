import assert from 'node:assert/strict';
import {countdown,remainingSeconds,updateClockNodes} from '../src/prototype/game-clock.js';
const start=Date.parse('2026-11-22T10:00:00Z');
assert.equal(countdown('2026-11-22T10:10:00Z',start),'10:00');
assert.equal(countdown('2026-11-22T10:00:05Z',start),'00:05');
assert.equal(countdown('2026-11-22T10:00:00Z',start),'00:00');
assert.equal(countdown('2026-11-22T10:00:00Z',start+20),'00:00');
assert.equal(countdown(null,start),'—');
assert.equal(remainingSeconds('invalid',start),null);
const node={dataset:{clockPaused:'false',deadlineAt:'2026-11-22T10:00:05Z'},classList:{values:new Set(),toggle(name,on){if(on)this.values.add(name);else this.values.delete(name);}},textContent:''};
const root={querySelectorAll:()=>[node]};
updateClockNodes(root,start);
assert.equal(node.textContent,'00:05');
assert.ok(node.classList.values.has('bn-clock-warning'));
node.dataset.clockPaused='true';
updateClockNodes(root,start+100_000);
assert.equal(node.textContent,'Pausado');
assert.ok(!node.classList.values.has('bn-clock-warning'));
console.log('Game clock HUD tests OK');
